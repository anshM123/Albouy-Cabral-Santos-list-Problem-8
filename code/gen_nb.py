"""Generate numba straight-line code for the Fourier coefficients of Phi and Psi (and their partial derivatives).

For a polynomial P(x) = sum_a c_a x^a we emit P(x) and Pabs(y) = sum_a |c_a| y^a (y >= 0).  On a box
|x - x0| <= r (componentwise):  |P(x) - P(x0)| <= Pabs(|x0| + r) - Pabs(|x0|),  since |x^a - x0^a| <= (|x0|+r)^a - |x0|^a.
Usage: python gen_nb.py a   -> nbcoef_a.py  (variables e, b, p, q; a-chart)
       python gen_nb.py f   -> nbcoef_f.py  (variables e, p, q; f-chart)
       python gen_nb.py fe  -> nbcoef_fe.py (variables eps = 1 - e, p, q; same f-chart polynomial)
"""
import sys
import sympy as sp

chart = sys.argv[1]
z = sp.symbols('z')
cu = (z + 1 / z) / 2
su = (z - 1 / z) / (2 * sp.I)


def ddu(expr):
    return sp.expand(sp.I * z * sp.diff(expr, z))


if chart == 'a':
    e, b, p, q = sp.symbols('e b p q', real=True)
    VARS = (e, b, p, q)
    r = 1 - e * cu
    Z = p * (cu - e) + b * q * su
    rho2 = sp.expand(r**2 - Z**2)
    Phi = sp.expand(ddu(sp.expand(r**2))**2 * rho2)
    Psi = sp.expand(ddu(rho2)**2)
elif chart.startswith('fm'):
    # Moebius-preconditioned f-chart: z_f = (z - c)/(1 - c z) (a disk automorphism fixing -1 and 1), c = MOB[chart].
    # P_w(w) = P_f(f(w)) * |1 - c e^{iw}|^12 is a trigonometric polynomial of degree <= 6 in w with the same real zeros
    # (with multiplicity) as P_f, and the same number of zeros inside the unit disk (as a function of z = e^{iw}).
    MOB = {'fm5': sp.Rational(1, 2), 'fm8': sp.Rational(4, 5), 'fm7': sp.Rational(7, 10), 'fm6': sp.Rational(3, 5)}
    cc_ = MOB[chart]
    e, p, q = sp.symbols('e p q', real=True)
    VARS = (e, p, q)
    zeta = p * cu + q * su
    sig2 = sp.expand(1 - zeta**2)
    D = 1 + e * cu
    B = sp.expand(ddu(sig2) + 2 * e * (su - q * zeta))
    Phi0 = sp.expand(4 * (1 + e)**2 * e**2 * su**2 * sig2)
    Psi0 = sp.expand(D**2 * B**2)
    w_ = sp.symbols('w_')
    def mob(F):
        G = F.subs(z, w_).subs(w_, (z - cc_) / (1 - cc_ * z))
        G = sp.cancel(sp.together(G * ((1 - cc_ * z) * (1 - cc_ / z))**6))
        return sp.expand(G)
    Phi = mob(Phi0)
    Psi = mob(Psi0)
elif chart == 'fe':
    # f-chart written in eps = 1 - e (no cancellation as e -> 1); the box variable stays e, eps = 1 - e
    eps, p, q = sp.symbols('eps p q', real=True)
    VARS = (eps, p, q)
    e = 1 - eps
    zeta = p * cu + q * su
    sig2 = sp.expand(1 - zeta**2)
    D = 1 + e * cu
    B = sp.expand(ddu(sig2) + 2 * e * (su - q * zeta))
    Phi = sp.expand(4 * (1 + e)**2 * e**2 * su**2 * sig2)
    Psi = sp.expand(D**2 * B**2)
else:
    e, p, q = sp.symbols('e p q', real=True)
    VARS = (e, p, q)
    zeta = p * cu + q * su
    sig2 = sp.expand(1 - zeta**2)
    D = 1 + e * cu
    B = sp.expand(ddu(sig2) + 2 * e * (su - q * zeta))
    Phi = sp.expand(4 * (1 + e)**2 * e**2 * su**2 * sig2)
    Psi = sp.expand(D**2 * B**2)


def real_form(F):
    P = sp.Poly(sp.expand(F * z**6), z)
    c = {k - 6: sp.expand(P.coeff_monomial(z**k)) for k in range(13)}
    a = [sp.expand(sp.re(c[0]))] + [sp.expand(2 * sp.re(c[k])) for k in range(1, 7)]
    s = [sp.Integer(0)] + [sp.expand(-2 * sp.im(c[k])) for k in range(1, 7)]
    return a, s


polys = {}      # (deriv_index or -1, f, part, k) -> sympy expr
FS = [real_form(Phi), real_form(Psi)]
for f in range(2):
    for part in range(2):
        for k in range(7):
            ex = FS[f][part][k]
            polys[(-1, f, part, k)] = ex
            for vi, v in enumerate(VARS):
                polys[(vi, f, part, k)] = sp.expand(sp.diff(ex, v))

names = [str(v) for v in VARS]
maxdeg = {n: 0 for n in names}
for ex in polys.values():
    if ex == 0:
        continue
    P = sp.Poly(ex, *VARS)
    for mon in P.monoms():
        for n, d in zip(names, mon):
            maxdeg[n] = max(maxdeg[n], d)


def emit(fn_name, use_abs):
    L = [f'@njit(cache=True, fastmath=False)',
         f'def {fn_name}({", ".join(names)}, out):']
    for n in names:
        L.append(f'    {n}0 = 1.0')
        for d in range(1, maxdeg[n] + 1):
            L.append(f'    {n}{d} = {n}{d-1} * {n}')
    for key, ex in polys.items():
        di, f, part, k = key
        idx = f'{di + 1}, {f}, {part}, {k}'
        if ex == 0:
            L.append(f'    out[{idx}] = 0.0')
            continue
        P = sp.Poly(ex, *VARS)
        terms = []
        for mon, coef in P.terms():
            c = float(abs(coef)) if use_abs else float(coef)
            mono = ' * '.join(f'{n}{d}' for n, d in zip(names, mon) if d > 0) or '1.0'
            terms.append(f'{c!r} * {mono}')
        L.append(f'    out[{idx}] = ' + ' + '.join(terms))
    L.append('')
    return L


src = ['"""Generated by gen_nb.py (chart %s). out[d+1, f, part, k]: d = -1 value, d = 0.. partial derivatives."""' % chart,
       'from numba import njit', '', f'NV = {len(VARS)}', '']
src += emit('coef_val', False)
src += emit('coef_abs', True)
open(f'nbcoef_{chart}.py', 'w').write('\n'.join(src) + '\n')
print(f'written nbcoef_{chart}.py; max degrees', maxdeg, '; polynomials', len(polys))
