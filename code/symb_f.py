"""f-chart (true anomaly f, pericentre distance q = 1, circle radius kappa = R/q, t = kappa^2/(1+kappa^2)).

  r = (1+e)/D, D = 1 + e cos f,  zeta = P_z cos f + Q_z sin f,  sigma^2 = 1 - zeta^2,  rho^2 = r^2 sigma^2,
  Pol * D^8/(1+e)^4 = PhiF - kappa^2 PsiF,
  PhiF = 4 (1+e)^2 e^2 sin^2 f sigma^2,   PsiF = D^2 B^2,   B = (sigma^2)' + 2 e (sin f - Q_z zeta).
f_t = (1-t) PhiF - t PsiF.  Coefficients are polynomials in (e, p = P_z, q = Q_z); e in [0, 1] (e = 1: parabola).
Writes coeffsF.py: allcF(e, p, q) -> (V, D) in the same layout as coeffs3_ce.allc (D over variables e, p, q).
"""
import sympy as sp

e, p, q = sp.symbols('e p q', real=True)
z = sp.symbols('z')
cf = (z + 1 / z) / 2
sf = (z - 1 / z) / (2 * sp.I)


def ddf(expr):
    return sp.expand(sp.I * z * sp.diff(expr, z))


zeta = p * cf + q * sf
sig2 = sp.expand(1 - zeta**2)
D = 1 + e * cf
B = sp.expand(ddf(sig2) + 2 * e * (sf - q * zeta))
PhiF = sp.expand(4 * (1 + e)**2 * e**2 * sf**2 * sig2)
PsiF = sp.expand(D**2 * B**2)

# consistency check against the unsimplified bracket (sigma^2)' D + 2 e sin f sigma^2
Bfull = sp.expand(ddf(sig2) * D + 2 * e * sf * sig2)
assert sp.expand(Bfull - B) == 0, "bracket simplification failed"


def real_form(F):
    P = sp.Poly(sp.expand(F * z**6), z)
    assert P.degree() <= 12
    c = {k - 6: sp.expand(P.coeff_monomial(z**k)) for k in range(13)}
    a = [sp.expand(sp.re(c[0]))] + [sp.expand(2 * sp.re(c[k])) for k in range(1, 7)]
    s = [sp.Integer(0)] + [sp.expand(-2 * sp.im(c[k])) for k in range(1, 7)]
    return a, s


V = [real_form(PhiF), real_form(PsiF)]
lines = ['"""Generated by symb_f.py (f-chart)."""', '', 'def allcF(e, p, q):']
lines.append('    V = [[[0] * 7 for _ in range(2)] for _ in range(2)]')
lines.append('    D = [[[[0] * 7 for _ in range(2)] for _ in range(2)] for _ in range(3)]')
for f in range(2):
    for part in range(2):
        for k in range(7):
            ex = V[f][part][k]
            if ex != 0:
                lines.append(f'    V[{f}][{part}][{k}] = {sp.pycode(sp.horner(ex))}')
            for vi, var in enumerate((e, p, q)):
                d = sp.expand(sp.diff(ex, var))
                if d != 0:
                    lines.append(f'    D[{vi}][{f}][{part}][{k}] = {sp.pycode(sp.horner(d))}')
lines.append('    return V, D')
open('coeffsF.py', 'w').write('\n'.join(lines) + '\n')
print('written coeffsF.py')
