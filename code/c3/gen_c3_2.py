"""Second-order coefficient data for the C3 / KQ polynomial charts (same charts as gen_c3.py).

For chart C with G = sum_k c_k(x) r^k (x = the four box variables, see gen_c3.chart_def), writes nbcoef_c3_<C>_2.py:
  coef_val2(x, out): out[0, k] = c_k, out[1 + v, k] = d c_k / dx_v (v = 0..3), out[5 + m, k] = second derivative
                     number m (sorted pairs (0,0), (0,1), ..., (3,3); 10 of them), all signed, at x;
  coef_abs2(y, out): absolute-value polynomials (y >= 0) of the value (0), first (1..4), second (5..14) and third
                     derivatives (15..34; sorted triples (0,0,0), (0,0,1), ..., (3,3,3); 20 of them).
usage: python gen_c3_2.py CHART [CHART ...]"""
import itertools
import sys
import sympy as sp
from gen_c3 import chart_def

PAIRS = sorted(set(tuple(sorted(x)) for x in itertools.product(range(4), repeat=2)))
TRIPLES = sorted(set(tuple(sorted(x)) for x in itertools.product(range(4), repeat=3)))
assert len(PAIRS) == 10 and len(TRIPLES) == 20


def main(chart):
    D = chart_def(chart)
    G, box, root = D['G'], D['box'], D['root']
    GP = sp.Poly(G, root)
    deg = GP.degree()
    coeffs = [sp.expand(GP.coeff_monomial(root**k)) for k in range(deg + 1)]
    for c in coeffs:
        assert not (c.free_symbols - set(box)), (chart, c.free_symbols - set(box))
    vals = {}; absp = {}
    for k, c in enumerate(coeffs):
        d1 = [sp.expand(sp.diff(c, box[v])) for v in range(4)]
        d2 = [sp.expand(sp.diff(c, box[i], box[j])) for i, j in PAIRS]
        d3 = [sp.expand(sp.diff(c, box[i], box[j], box[m])) for i, j, m in TRIPLES]
        for s_, ex in enumerate([c] + d1 + d2):
            vals[(s_, k)] = ex
        for s_, ex in enumerate([c] + d1 + d2 + d3):
            absp[(s_, k)] = ex
    names = [str(s) for s in box]
    maxdeg = {n: 0 for n in names}
    nterms = 0
    for ex in list(absp.values()):
        if ex == 0:
            continue
        Pp = sp.Poly(ex, *box)
        nterms = max(nterms, len(Pp.terms()))
        for mon in Pp.monoms():
            for n, d in zip(names, mon):
                maxdeg[n] = max(maxdeg[n], d)

    def emit(fn, polys, use_abs):
        L = ['@njit(cache=True)', f'def {fn}(x, out):']
        for i, n in enumerate(names):
            if maxdeg[n] >= 1:
                L.append(f'    {n}1 = x[{i}]')
            for d in range(2, maxdeg[n] + 1):
                L.append(f'    {n}{d} = {n}{d-1} * {n}1')
        for (dv, k), ex in polys.items():
            if ex == 0:
                L.append(f'    out[{dv}, {k}] = 0.0')
                continue
            terms = []
            for mon, coef in sp.Poly(ex, *box).terms():
                cval = float(abs(coef)) if use_abs else float(coef)
                mono = ' * '.join(f'{n}{d}' for n, d in zip(names, mon) if d > 0) or '1.0'
                terms.append(f'{cval!r} * {mono}')
            L.append(f'    out[{dv}, {k}] = ' + ' + '.join(terms))
        L.append('')
        return L

    src = [f'"""Generated by gen_c3_2.py, chart {chart}: second-order data of G = sum_k c_k(x) {root}^k, box vars '
           f'{names}, degree {deg}; max terms per polynomial {nterms}."""', 'from numba import njit', '',
           f'DEG = {deg}', f'BOX = {names!r}', f'MAXTERMS = {nterms}', '']
    src += emit('coef_val2', vals, False)
    src += emit('coef_abs2', absp, True)
    open(f'nbcoef_c3_{chart}_2.py', 'w').write('\n'.join(src) + '\n')
    print(chart, 'written nbcoef_c3_%s_2.py; degree' % chart, deg, 'max terms', nterms, 'max degrees', maxdeg, flush=True)


if __name__ == '__main__':
    for ch in sys.argv[1:]:
        main(ch)
