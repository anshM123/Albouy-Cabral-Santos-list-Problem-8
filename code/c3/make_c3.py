"""Write nbeng_c3_<chart>.py: Rolle-run root-count certificate for G(r; x) = sum_k c_k(x) r^k on a root interval
[rlo, rhi] (linear, not periodic), uniformly over a parameter box x in [x0lo, x0hi] x ... x [x3lo, x3hi].

Enclosures (same scheme as nb_cert.py):
  coefficients at the float box centre, radius 1e-13 * Pabs(|x_c|) (evaluation rounding);
  parameter variation by the mean-value form  sum_v rr_v (|dG/dx_v (r)| + sum_k w_{v,k} |d^j r^k|), with
  w_{v,k} = Pabs_v(|x_c| + rr) - Pabs_v(|x_c|) (absolute-value polynomial of dc_k/dx_v), rr padded for the float centre;
  arc remainder h |G^(j+1)(r_m)| + h^2/2 sup |G^(j+2)|, sup bounded by sum_k cmax_k (k)_(j+2) (|r_m| + h)^(k-j-2);
  float padding 1e-12 (mag + radius).  Arcs overlap by ARC_PAD and cover [rlo - pad, rhi + pad].
A run of consecutive arcs on which G^(j) has one strict sign contains at most j zeros of G (with multiplicity);
dp_linear returns the minimal sum over a partition into such runs.
usage: python make_c3.py CHART [CHART ...]"""
import sys

SRC = '''"""Generated by make_c3.py for chart {chart}."""
import math
import numpy as np
from numba import njit
from nbcoef_c3_{chart} import coef_val, coef_abs, DEG

ARC_PAD = 1e-12


@njit(cache=True)
def box_coeffs(x0lo, x0hi, x1lo, x1hi, x2lo, x2hi, x3lo, x3hi):
    lo = np.array([x0lo, x1lo, x2lo, x3lo]); hi = np.array([x0hi, x1hi, x2hi, x3hi])
    xc = 0.5 * (lo + hi)
    rr = 0.5 * (hi - lo) * (1 + 1e-12) + 1e-15 * (np.abs(xc) + 1.0)
    aa = np.abs(xc); ab = aa + rr
    val = np.zeros((5, DEG + 1)); a0 = np.zeros((5, DEG + 1)); a1 = np.zeros((5, DEG + 1))
    coef_val(xc, val); coef_abs(aa, a0); coef_abs(ab, a1)
    cmid = val[0].copy()
    crad = 1e-13 * a0[0] + 1e-300
    cmax = a1[0] * (1 + 1e-12)
    dcen = val[1:].copy()
    dwid = (a1[1:] - a0[1:]) * (1 + 1e-12) + 1e-13 * a1[1:]
    return cmid, crad, dcen, dwid, cmax, rr


@njit(cache=True)
def ff(k, j):
    p = 1.0
    for i in range(j):
        p *= (k - i)
    return p


@njit(cache=True)
def root_signs(cmid, crad, dcen, dwid, cmax, rr, um, hh, J):
    M = um.size
    sg = np.zeros((J + 1, M), dtype=np.int64)
    hop = np.ones(M, dtype=np.bool_)
    for i in range(M):
        y = um[i]; h = hh[i]; ay = abs(y)
        vc = np.empty(J + 2); rad = np.empty(J + 2)
        for j in range(J + 2):
            s = 0.0; mag = 0.0; rd = 0.0
            g = np.zeros(4); w = np.zeros(4)
            for k in range(j, DEG + 1):
                f = ff(k, j)
                pw = y ** (k - j) * f
                apw = ay ** (k - j) * f
                s += cmid[k] * pw
                mag += abs(cmid[k]) * apw
                rd += crad[k] * apw
                for v in range(4):
                    g[v] += dcen[v, k] * pw
                    w[v] += dwid[v, k] * apw
            prad = 0.0
            for v in range(4):
                prad += rr[v] * (abs(g[v]) + w[v])
            tot = rd + prad
            tot = tot + 1e-12 * (mag + tot)
            vc[j] = s; rad[j] = tot
        for j in range(J + 1):
            if abs(vc[j]) > rad[j]:
                hop[i] = False
            B2 = 0.0
            for k in range(j + 2, DEG + 1):
                B2 += cmax[k] * ff(k, j + 2) * (ay + h) ** (k - j - 2)
            B2 *= 1 + 1e-12
            m1 = abs(vc[j + 1]) + rad[j + 1]
            tail = rad[j] + h * m1 + 0.5 * h * h * B2
            tail = tail + 1e-15 * (abs(vc[j]) + tail)
            lo = vc[j] - tail
            hi = vc[j] + tail
            if lo > 0:
                sg[j, i] = 1
            elif hi < 0:
                sg[j, i] = -1
    any_hopeless = False
    for i in range(M):
        if hop[i]:
            any_hopeless = True
    return sg, any_hopeless


@njit(cache=True)
def dp_linear(sg):
    J1, M = sg.shape
    dp = np.full(M + 1, 999.0)
    dp[0] = 0.0
    rs = np.zeros(J1, dtype=np.int64)
    for i in range(M):
        best = 999.0
        for j in range(J1):
            v = sg[j, i]
            if v == 0:
                continue
            if i == 0 or sg[j, i - 1] != v:
                rs[j] = i
            cand = dp[rs[j]] + j
            if cand < best:
                best = cand
        dp[i + 1] = best
    return dp[M]


@njit(cache=True)
def count(x0lo, x0hi, x1lo, x1hi, x2lo, x2hi, x3lo, x3hi, rlo, rhi, J, M0, rounds, cap, target):
    cmid, crad, dcen, dwid, cmax, rr = box_coeffs(x0lo, x0hi, x1lo, x1hi, x2lo, x2hi, x3lo, x3hi)
    left = rlo + np.arange(M0) * ((rhi - rlo) / M0)
    width = np.full(M0, (rhi - rlo) / M0)
    best = 999.0
    for rd in range(rounds + 1):
        sg, hopeless = root_signs(cmid, crad, dcen, dwid, cmax, rr, left + width / 2, width / 2 + ARC_PAD, J)
        best = min(best, dp_linear(sg))      # every round's bound is valid; keep the smallest
        if best <= target:
            return True, best
        if rd == rounds or hopeless or left.size > cap:
            break
        nsel = 0
        for i in range(left.size):
            if sg[0, i] == 0:
                nsel += 1
        if nsel == 0:
            break
        nl = np.empty(left.size + nsel); nw = np.empty(left.size + nsel)
        m = 0
        for i in range(left.size):
            if sg[0, i] == 0:
                nl[m] = left[i]; nw[m] = width[i] / 2; m += 1
                nl[m] = left[i] + width[i] / 2; nw[m] = width[i] / 2; m += 1
            else:
                nl[m] = left[i]; nw[m] = width[i]; m += 1
        left = nl; width = nw
    return False, best
'''

for chart in sys.argv[1:]:
    open(f'nbeng_c3_{chart}.py', 'w').write(SRC.format(chart=chart))
    print('written', f'nbeng_c3_{chart}.py')
