"""Generate nbcoef_a2.py: second-order data for the a-chart Fourier coefficients (chart 0 of nb_cert).

Same polynomials as gen_nb.py chart a (variables e, b, p, q with b = sqrt(1 - e^2) treated as an independent
variable; Phi and Psi; cos/sin parts; k = 0..6), with
  coef_val2(e, b, p, q, out): out[0] value, out[1..4] first derivatives, out[5..14] second derivatives in the sorted
                              pairs (ee, eb, ep, eq, bb, bp, bq, pp, pq, qq), all signed, at the given point;
  coef_abs2(e, b, p, q, out): absolute-value polynomials of the value (0), first (1..4), second (5..14) and third
                              derivatives (15..34, sorted triples).
Usage: python gen_nb2a.py   -> nbcoef_a2.py
"""
import itertools
import sympy as sp

z = sp.symbols('z')
cu = (z + 1 / z) / 2
su = (z - 1 / z) / (2 * sp.I)


def ddu(expr):
    return sp.expand(sp.I * z * sp.diff(expr, z))


e, b, p, q = sp.symbols('e b p q', real=True)
VARS = (e, b, p, q)
r = 1 - e * cu
Z = p * (cu - e) + b * q * su
rho2 = sp.expand(r**2 - Z**2)
Phi = sp.expand(ddu(sp.expand(r**2))**2 * rho2)
Psi = sp.expand(ddu(rho2)**2)


def real_form(F):
    P = sp.Poly(sp.expand(F * z**6), z)
    c = {k - 6: sp.expand(P.coeff_monomial(z**k)) for k in range(13)}
    a = [sp.expand(sp.re(c[0]))] + [sp.expand(2 * sp.re(c[k])) for k in range(1, 7)]
    s = [sp.Integer(0)] + [sp.expand(-2 * sp.im(c[k])) for k in range(1, 7)]
    return a, s


SECOND = sorted(set(tuple(sorted(x)) for x in itertools.product(range(4), repeat=2)))
THIRD = sorted(set(tuple(sorted(x)) for x in itertools.product(range(4), repeat=3)))
assert len(SECOND) == 10 and len(THIRD) == 20

vals = {}      # (slot, f, part, k) -> expr for coef_val2 (slots 0..9)
absp = {}      # (slot, f, part, k) -> expr for coef_abs2 (slots 0..19)
FS = [real_form(Phi), real_form(Psi)]
for f in range(2):
    for part in range(2):
        for k in range(7):
            ex = FS[f][part][k]
            d1 = [sp.expand(sp.diff(ex, v)) for v in VARS]
            d2 = [sp.expand(sp.diff(ex, VARS[i], VARS[j])) for i, j in SECOND]
            d3 = [sp.expand(sp.diff(ex, VARS[i], VARS[j], VARS[m])) for i, j, m in THIRD]
            for s_, x in enumerate([ex] + d1 + d2):
                vals[(s_, f, part, k)] = x
            for s_, x in enumerate([ex] + d1 + d2 + d3):
                absp[(s_, f, part, k)] = x

names = [str(v) for v in VARS]
maxdeg = {n: 0 for n in names}
for ex in list(vals.values()) + list(absp.values()):
    if ex == 0:
        continue
    for mon in sp.Poly(ex, *VARS).monoms():
        for n, d in zip(names, mon):
            maxdeg[n] = max(maxdeg[n], d)


def emit(fn_name, polys, use_abs):
    L = ['@njit(cache=True, fastmath=False)', f'def {fn_name}({", ".join(names)}, out):']
    for n in names:
        L.append(f'    {n}0 = 1.0')
        for d in range(1, maxdeg[n] + 1):
            L.append(f'    {n}{d} = {n}{d-1} * {n}')
    for key, ex in polys.items():
        s_, f, part, k = key
        idx = f'{s_}, {f}, {part}, {k}'
        if ex == 0:
            L.append(f'    out[{idx}] = 0.0')
            continue
        terms = []
        for mon, coef in sp.Poly(ex, *VARS).terms():
            c = float(abs(coef)) if use_abs else float(coef)
            mono = ' * '.join(f'{n}{d}' for n, d in zip(names, mon) if d > 0) or '1.0'
            terms.append(f'{c!r} * {mono}')
        L.append(f'    out[{idx}] = ' + ' + '.join(terms))
    L.append('')
    return L


nterms = max(len(sp.Poly(x, *VARS).terms()) for x in absp.values() if x != 0)
tdeg = max(sum(m) for x in absp.values() if x != 0 for m in sp.Poly(x, *VARS).monoms())
src = ['"""Generated by gen_nb2a.py (chart a, second-order data).  Variables (e, b, p, q).  coef_val2: out[0] value,',
       'out[1..4] first derivatives, out[5..14] second derivatives (sorted pairs).  coef_abs2: absolute-value polynomials',
       f'of the value, first, second and third (out[15..34], sorted triples) derivatives.  Max terms {nterms}, max total degree {tdeg}."""',
       'from numba import njit', '']
src += emit('coef_val2', vals, False)
src += emit('coef_abs2', absp, True)
open('nbcoef_a2.py', 'w').write(chr(10).join(src) + chr(10))
print('written nbcoef_a2.py; max degrees', maxdeg, '; max terms', nterms, '; max total degree', tdeg)
